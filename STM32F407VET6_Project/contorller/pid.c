/**
 ******************************************************************************
 * @file    pid.c
 * @brief   通用 PID 实现（移植自大疆 RoboMaster 开源 PID）
 * @details
 *   PID_POSITION：u = Kp*e + Ki*Σe + Kd*(e-e1)，输出绝对值，适合“位置/角度/像素误差”；
 *   PID_DELTA   ：Δu = Kp*(e-e1) + Ki*e + Kd*(e-2e1+e2)，输出增量累加，适合速度环。
 *   本工程云台 x/y 用的都是 PID_DELTA（见 Dloud_deck.c 的 PID_init 调用）。
 * @note
 *   1. 两处限幅：积分限幅 max_iout 防饱和，输出限幅 max_out 防超调；
 *   2. 增量式必须保证 pid->out 不被外部清零，否则累积量会丢失；
 *   3. 调用周期要固定（本工程 10 ms），周期一变等效参数就变。
 ******************************************************************************
 */

